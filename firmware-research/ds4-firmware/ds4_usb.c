void ds4_set_device_address(const uint8_t addr[6])
{
	unsigned i;

	for (i = 0; i < 6; i++) {
		feature_12[1 + i] = addr[i];
		feature_81[1 + i] = addr[i];
	}
}

void ds4_address_from_uid(const uint8_t *uid, unsigned len, uint8_t addr[6])
{
	unsigned i;

	for (i = 0; i < 6; i++) {
		addr[i] = 0;
	}
	for (i = 0; i < len; i++) {
		addr[i % 6] ^= uid[i];
	}
	addr[5] = (uint8_t)((addr[5] & 0xFC) | 0x02);
}

uint16_t ds4_fixed_feature(uint8_t report_id, uint8_t scratch[64], const uint8_t **data)
{
	unsigned i, j;

	switch (report_id) {
	case 0x12:
		*data = feature_12;
		return sizeof(feature_12);
	case 0x02:
		*data = feature_02;
		return sizeof(feature_02);
	case 0xA3:
		*data = feature_a3;
		return sizeof(feature_a3);
	case 0x81:
		*data = feature_81;
		return sizeof(feature_81);
	default:
		break;
	}
	/* Any other feature report declared by the descriptor: all zeros. */
	for (i = 0; i < sizeof(feature_sizes); i += 2) {
		if (feature_sizes[i] == report_id) {
			unsigned n = feature_sizes[i + 1] + 1u;

			for (j = 0; j < n; j++) {
				scratch[j] = 0;
			}
			scratch[0] = report_id;
			*data = scratch;
			return (uint16_t)n;
		}
	}
	return 0;
}
